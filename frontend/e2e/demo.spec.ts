import {test, expect} from '@playwright/test'

test('two photos, explicit confirmation, due reminder, taken and stop', async ({page}) => {
  await page.goto('/')
  await expect(page.getByText('Sample mode · simulated reading')).toBeVisible()
  await page.getByRole('button', {name:'Add a photo', exact:true}).click()
  await page.locator('.samples').getByRole('button', {name:'Medication guide', exact:true}).click()
  await expect(page.getByLabel('Name', {exact:true})).toHaveValue('Demo Medication A')
  await expect(page.getByText('SIMULATED SAMPLE READING · UNVERIFIED')).toBeVisible()
  await expect(page.getByRole('button', {name:'Confirm & activate reminders'})).toBeDisabled()
  await expect(page.getByLabel('Reminder time 1', {exact:true})).toHaveValue('')
  await page.getByLabel('Reminder time 1', {exact:true}).fill('23:50')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', {name:'Confirm & activate reminders'}).click()
  await expect(page.getByRole('status')).toContainText('Confirmed.')
  await page.locator('.samples').getByRole('button', {name:'Supplement label', exact:true}).click()
  await expect(page.getByLabel('Name', {exact:true})).toHaveValue('Demo Supplement B')
  await page.getByLabel('Reminder time 1', {exact:true}).fill('23:55')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', {name:'Confirm & activate reminders'}).click()
  await page.getByRole('button', {name:'Today', exact:true}).click()
  await expect(page.getByRole('heading', {name:'Demo Medication A', exact:true})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Demo Supplement B', exact:true})).toBeVisible()
  await page.getByRole('button', {name:'Jump to next reminder'}).click()
  await expect(page.getByText('DEMO TIME · SEOUL')).toBeVisible()
  await expect(page.getByRole('region', {name:'Due reminders'})).toBeVisible()
  await page.getByRole('button', {name:'Mark as taken'}).click()
  await expect(page.getByText('Reported taken', {exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByText('Reported taken', {exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/today.png', fullPage:true})
  await page.getByRole('button', {name:'My routines', exact:true}).click()
  await page.locator('.routine-grid article').filter({hasText:'Demo Supplement B'}).getByRole('button', {name:'Stop reminders'}).click()
  await expect(page.getByRole('status')).toContainText('Routine stopped')
  await page.getByRole('button', {name:'Today', exact:true}).click()
  await expect(page.getByRole('heading', {name:'Demo Supplement B', exact:true})).toHaveCount(0)
  await page.setViewportSize({width:390, height:844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({path:'test-results/mobile.png', fullPage:true})
})

test('failed extraction offers manual confirmation without claiming AI success', async ({page}) => {
  await page.route('**/api/documents/*/extract', route => route.fulfill({status:503, contentType:'application/json', body:JSON.stringify({detail:'Image reading failed. Enter the details manually.'})}))
  await page.goto('/')
  await page.getByRole('button', {name:'Add a photo', exact:true}).click()
  await page.locator('.samples').getByRole('button', {name:'Supplement label', exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Enter the details manually')
  await page.getByLabel('Name', {exact:true}).fill('Manually entered synthetic supplement')
  await page.getByLabel('Amount per dose', {exact:true}).fill('1 capsule')
  await page.getByLabel('Reminder time 1', {exact:true}).fill('22:00')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', {name:'Confirm & activate reminders'}).click()
  await expect(page.getByRole('status')).toContainText('Confirmed.')
  await page.getByRole('button', {name:'My routines', exact:true}).click()
  await expect(page.getByText('Manually entered & confirmed')).toBeVisible()
  await page.setViewportSize({width:390, height:844})
  await page.getByRole('button', {name:'Add from a photo', exact:true}).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({path:'test-results/review-mobile.png', fullPage:true})
})
